/**
 * נעילת גלילת הרקע, בספירת עומק.
 *
 * **הבאג שזה סוגר.** קודם כל רכיב שנעל שמר לעצמו את `document.body.style.overflow`
 * שהיה לפניו והחזיר אותו בסגירה. זה נכון לרכיב בודד ושגוי לשניים מקוננים, וזה
 * המבנה האמיתי באפליקציה: נגן הסרטונים נפתח כ-portal אח *בזמן* שגיליון
 * ההחלפה עדיין פתוח.
 *
 *   1. הגיליון נועל   — שומר previous='' ומציב 'hidden'
 *   2. הנגן נועל מעליו — שומר previous='hidden' (הנעילה של הגיליון!) ומציב 'hidden'
 *   3. הגיליון נסגר ראשון — מחזיר '', והרקע נגלל מתחת לנגן שעדיין פתוח
 *   4. הנגן נסגר       — מחזיר 'hidden', ומכאן הדף **נעול לצמיתות** בלי מודל
 *
 * שלב 4 הוא הנזק: אין יותר מודל, אין מי שישחרר, והמסך מת עד רענון. באפליקציה
 * שרצה כ-PWA מותקן זה אומר לצאת ולהיכנס באמצע אימון.
 *
 * **למה מונה ולא דגל בוליאני.** דגל היה נכשל באותו שלב 3: הרכיב הפנימי לא
 * יודע אם הוא האחרון שנעול. רק ספירה יודעת. ה-`overflow` המקורי נקרא פעם
 * אחת בלבד — במעבר 0→1 — ולכן הוא תמיד הערך שקדם לכל המודלים, ולא נעילה של
 * מודל אחר שנקראה בטעות כמצב הבסיס.
 *
 * **למה מודול ולא hook.** המצב חייב להיות משותף לכל הנועלים, ו-hook היה נותן
 * לכל רכיב עותק משלו — כלומר בדיוק הבאג מחדש. הסגירה על משתני מודול היא מה
 * שהופך את המונה לאחד.
 */

/** כמה נעילות פעילות ברגע זה */
let depth = 0

/** ערך ה-overflow שקדם לנעילה הראשונה. נקרא רק במעבר 0→1 */
let restoreTo = ''

/**
 * נועל את גלילת הרקע, ומחזיר את פונקציית השחרור.
 *
 * החתימה הזו (נעילה מחזירה שחרור) נבחרה כדי שאפשר יהיה להחזיר אותה ישירות
 * מ-`useEffect` — הצורה שהכי קשה לטעות בה, כי אין דרך לנעול בלי לכתוב גם את
 * מסלול השחרור.
 *
 * השחרור חסין לקריאה כפולה. בלעדיו קריאה שנייה הייתה מורידה את המונה פעם
 * נוספת ומשחררת נעילה של מודל אחר שעדיין פתוח — כשל שקט שנראה כמו "לפעמים
 * הרקע נגלל".
 */
export function lockBodyScroll(): () => void {
  if (depth === 0) {
    restoreTo = document.body.style.overflow
    document.body.style.overflow = 'hidden'
  }
  depth += 1

  let released = false
  return function release(): void {
    if (released) return
    released = true
    depth -= 1
    if (depth === 0) document.body.style.overflow = restoreTo
  }
}
