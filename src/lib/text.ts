/**
 * נרמול טקסט לחיפוש.
 *
 * גרשיים וגרשים יורדים כי בעברית הם חלק מהמילה ולא ממנה: מי שמחפש "ק״ג" ומי
 * שמחפש "קג" מתכוונים לאותו דבר, ומי שמחפש "יד אח׳" לא אמור לזכור איזה סוג
 * גרש נכתב בקטלוג.
 *
 * הפונקציה הזו הייתה משוכפלת בשבע נקודות — שש מסכים ושכבת השאילתות — ולכן כל
 * שינוי בכללי הנרמול (למשל התעלמות ממקפים) היה דורש שבע עריכות, ושכחה של אחת
 * מהן הייתה מייצרת מסך שמוצא משהו אחר מהשאר.
 */
export function normalize(text: string): string {
  return text.toLowerCase().replace(/[״׳"']/g, '').trim()
}
