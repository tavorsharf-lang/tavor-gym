/**
 * נרמול טקסט לחיפוש.
 *
 * גרשיים וגרשים יורדים כי בעברית הם חלק מהמילה ולא ממנה: מי שמחפש "ק״ג" ומי
 * שמחפש "קג" מתכוונים לאותו דבר, ומי שמחפש "יד אח׳" לא אמור לזכור איזה סוג
 * גרש נכתב בקטלוג.
 *
 * הפונקציה הזו הייתה משוכפלת בשבע נקודות — שש מסכים ושכבת השאילתות — ולכן כל
 * שינוי בכללי הנרמול (למשל התעלמות ממקפים) היה דורש שבע עריכות, ושכחה של אחת
 * מהן הייתה מייצרת מסך שמוצא משהו אחר מהשאר.
 */
export function normalize(text: string): string {
  return text.toLowerCase().replace(/[״׳"']/g, '').trim()
}

/*
  מספר קטן בתוך משפט נכתב במילה ולא בספרה.

  "נמצא ב2 תוכניות" ו"2 שרירים לא כוסו" נקראים רע — ספרה קוטעת את המשפט,
  ואחרי אות שימוש היא גם נצמדת אליה. מעל עשר המילה כבר ארוכה מהמספר וההפך
  נכון, ולכן שם חוזרים לספרה.

  מה שלא עובר כאן: מספרים שהם *נתון* ולא חלק ממשפט — "3 תרגילים · 11 סטים"
  בשורת כיסוי, משקלים, וספירת סטים. שם הספרה היא התוכן, היא מיושרת בעמודה
  עם tnum, ומילה במקומה הייתה מקשה על ההשוואה בין שורות.

  שתי נטיות כי לעברית יש שתיים, והבחירה היא לפי מין *הנספר*: תרגיל, שריר,
  סט ובלוק זכר; תוכנית ודקה נקבה.
*/
const FEMININE = ['', 'אחת', 'שתי', 'שלוש', 'ארבע', 'חמש', 'שש', 'שבע', 'שמונה', 'תשע', 'עשר']
const MASCULINE = [
  '',
  'אחד',
  'שני',
  'שלושה',
  'ארבעה',
  'חמישה',
  'שישה',
  'שבעה',
  'שמונה',
  'תשעה',
  'עשרה',
]

/** "שתי" · "שלוש" — לנספר ממין נקבה (תוכנית, דקה) */
export function countFeminine(n: number): string {
  return FEMININE[n] ?? `${n}`
}

/** "שני" · "שלושה" — לנספר ממין זכר (תרגיל, שריר, סט, בלוק) */
export function countMasculine(n: number): string {
  return MASCULINE[n] ?? `${n}`
}
