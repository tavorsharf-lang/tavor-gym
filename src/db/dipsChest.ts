import type { Exercise } from './types'

/**
 * מקבילים במכונה חוזרים להיות תרגיל חזה.
 *
 * מיגרציה 10 העבירה את `dips` מ-`chest` ל-`triceps` על סמך כותרת הסרטון
 * ("Plate Loaded TRICEP Dips") והדגשים שבו. מאז נכנס למאגר כרטיס השרירים של
 * המכונה, והוא מודד את מה שהכותרת רק תיארה: **חזה תחתון 48%**, טרייספס 27%,
 * כתף קדמית 15%, מייצבים 10%. הכרטיס הוא המקור שמסך הכיסוי ומיון האחוז
 * קוראים ממנו, ולכן קבוצה שסותרת אותו גורמת לאפליקציה לספור את התרגיל תחת
 * שריר שהוא לא הראשי שלו — ולהכריז "חזה · לא נגעת" אחרי אימון שכן נגע בו.
 *
 * מודול נפרד ולא קוד בתוך המיגרציה, מאותה סיבה בדיוק כמו `catalogV10`
 * ו-`calfMerge`: מיגרציה רצה פעם אחת, אבל אותה המרה נחוצה שוב בכל **ייבוא
 * גיבוי**. קובץ שנוצר בין מיגרציה 10 למיגרציה 16 מחזיק `triceps`, ובלי
 * ההמרה כאן שחזור שלו היה מחזיר את הסיווג השגוי למסד שכבר תוקן. גיבוי ישן
 * יותר מחזיק `chest` ועובר כאן בלי שינוי.
 *
 * ‏`=== 'triceps'` ולא "כל ערך שאינו chest": השער הזה נוגע רק בערך שהאפליקציה
 * עצמה כתבה. מי שהעביר את התרגיל ידנית לקבוצה אחרת התכוון לזה, וזה שלו.
 */
export function withDipsChest(exercise: Exercise): Exercise {
  if (exercise.id !== 'dips' || exercise.muscleGroup !== 'triceps') return exercise
  /*
    הטריצפס עובר למשניים ולא נשאר גם וגם: שריר ראשי שמופיע גם ברשימת המשניים
    נספר פעמיים במסך הכיסוי. זה בדיוק הנימוק שנכתב במיגרציה 10, רק בכיוון
    ההפוך — ושם הוא הוציא את החזה.
  */
  const secondary = (exercise.secondaryMuscles ?? []).filter((m) => m !== 'chest')
  return {
    ...exercise,
    muscleGroup: 'chest',
    secondaryMuscles: secondary.includes('triceps') ? secondary : ['triceps', ...secondary],
  }
}
