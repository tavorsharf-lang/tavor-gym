/**
 * דגל ההתקנה הראשונה — מי רואה את מסך הפתיחה.
 *
 * שלושה מצבים, וההבחנה ביניהם היא כל העניין:
 *   • **המפתח חסר** — משתמש קיים. זו ברירת המחדל הבטוחה, ולכן אין כאן שום
 *     מסלול שבו מכשיר ותיק נופל בטעות למסך "ברוך הבא".
 *   • `'new'` — המסד נזרע זה עתה בדפדפן הזה. רק כאן מסך הפתיחה מופיע.
 *   • `'done'` — כבר ראה (או שנקבע לו במיגרציה שהוא ותיק).
 *
 * **למה ב-localStorage ולא ב-AppSettings.** הדגל חייב לשרוד `db.delete()`:
 * "מחק הכל" ו"ייבוא גיבוי" שניהם מוחקים את המסד ומריצים את הזריעה מחדש, ודגל
 * שיושב בטבלה היה נמחק איתם — כלומר כל איפוס יזום של תבור היה זורק לו את מסך
 * הזר בפנים. בונוס: `importData` עובד בטרנזקציה על טבלאות בלבד ולא נוגע
 * ב-localStorage, ולכן קובץ גיבוי לא נושא את הדגל איתו לשום מקום.
 *
 * **הכול נכשל סגור.** בגלישה פרטית ובדפדפנים שחוסמים אחסון כל גישה כאן זורקת,
 * ואז `isFirstRun()` מחזיר `false` — האפליקציה נפתחת רגיל בלי מסך פתיחה.
 * המחיר הוא הסבר שלא הוצג; החלופה היא מסך שמשתלט על Shell בגלל שגיאת אחסון.
 */

const KEY = 'tavor-gym:first-run'

type FirstRunState = 'new' | 'done'

function read(): string | null {
  try {
    return localStorage.getItem(KEY)
  } catch {
    return null
  }
}

function write(state: FirstRunState): void {
  try {
    localStorage.setItem(KEY, state)
  } catch {
    // אין איפה לסמן — מסך הפתיחה פשוט לא יופיע. עדיף על נפילה בעליית האפליקציה.
  }
}

/**
 * נקרא מ-`on('populate')`, כלומר בדיוק פעם אחת בחיי מסד.
 *
 * כותב **רק** כשהמפתח חסר, וזו ההגנה על תבור: אחרי "מחק הכל" הזריעה רצה שוב
 * והמפתח שלו כבר `'done'` — הוא לא יראה את מסך הפתיחה בשנית.
 */
export function markFirstRun(): void {
  if (read() === null) write('new')
}

/** סוגר את מסך הפתיחה לתמיד. נקרא גם מהמסך עצמו וגם מהמיגרציה. */
export function markFirstRunSeen(): void {
  write('done')
}

/** האם להציג את מסך הפתיחה. סינכרוני בכוונה — הוא רץ לפני כל שאילתה למסד. */
export function isFirstRun(): boolean {
  return read() === 'new'
}
