import { imageIdOf } from './exerciseImages'
import type { ExerciseImage } from './imageManifest'
import { MUSCLE_BREAKDOWN } from './muscleBreakdown'
import { muscleCardFor } from './muscleCards'
import type { MuscleCardImage } from './muscleImageManifest'
import { MUSCLE_TAXONOMY } from './subTargets'
import type { MuscleGroup } from './types'

/**
 * מפת העומס — האחוזים שעל הכרטיס, כשורות שאפשר לקרוא.
 *
 * הכרטיס עצמו כבר אומר את זה, וזו בדיוק הבעיה: הוא אומר את זה בטקסט קטן
 * שמודפס על איור, בשלוש-ארבע נקודות פזורות סביב הגוף. כדי לדעת מה עובד הכי
 * הרבה צריך לסרוק את התמונה בעיניים ולהשוות מספרים שלא יושבים זה מעל זה.
 * השורות כאן הן אותם מספרים בדיוק, ממוינים, עם הפס שמראה את היחס.
 *
 * **המקור למספרים הוא התמלול בלבד.** `MUSCLE_BREAKDOWN` הוא מה שמודפס על
 * 88 הכרטיסים, ואין כאן שום הערכה. מה שכן נגזר:
 *
 *   • **השם — תמיד שלנו.** הכרטיסים משתמשים ב-116 תוויות עבריות שונות לאותם
 *     שרירים: "לטיסימוס דורסי" ו"רחב גבי" הם אותו שריר, ו"מייצבים",
 *     "שרירי מייצבים" ו"מייצבי גו" הם אותו דבר בשלושה כרטיסים. הטקסונומיה
 *     כבר מכריעה שם אחד לכל שריר, וזה השם היחיד שמוצג. מה שמודפס על התמונה
 *     לא מופיע בשום שורה — שני שמות לאותו שריר במרחק סנטימטר זה מזה נקראים
 *     כשני שרירים, וזו בדיוק הסיבה שההכרעה קיימת.
 *   • **מיזוג.** שתי שורות שהטקסונומיה קוראת להן אותו שם הן שורה אחת,
 *     והאחוזים נסכמים. ראו `mergeSameMuscle`.
 *   • **הכרטיס האנטומי.** אותה טקסונומיה מובילה מהשם האנגלי אל אחד מ-45
 *     הכרטיסים, וזו התשובה ל"איפה השריר הזה בכלל יושב" — השאלה שעולה מיד
 *     אחרי "מעוינים 25%".
 *
 * ‏`card: null` הוא מצב לגיטימי ולא חוסר: המייצבים מופיעים על כרטיסים כשארית
 * ואין להם אנטומיה להראות. השורה מוצגת עם האחוז שלה ובלי תמונה.
 */

export interface LoadShare {
  /** השם שהאפליקציה משתמשת בו לשריר הזה, מהטקסונומיה. אין שם אחר. */
  name: string
  /** השם האנגלי כפי שמודפס על הכרטיס — הוא גם המפתח לטקסונומיה */
  en: string
  /**
   * מה שמודפס בעברית על הכרטיס, רק כשהוא שונה מ-`name`.
   *
   * **לא לתצוגה.** הוא נשאר בשדה כדי שאפשר יהיה לאתר מאיפה שורה הגיעה —
   * לבדיקות ולניפוי מול התמונה — וההחלטה של תבור מפורשת: על המסך מופיע רק
   * השם שהאפליקציה משתמשת בו.
   */
  printed: string | null
  /**
   * האחוז. לא מנורמל ולא מעוגל.
   *
   * שווה למה שמודפס, אלא אם כמה שורות על הכרטיס מדברות על אותו שריר לפי
   * הטקסונומיה שלנו — ואז זה הסכום שלהן. `parts` אומר כמה היו.
   */
  pct: number
  /** מכמה שורות על הכרטיס השורה הזו מורכבת. 1 = כפי שמודפס. */
  parts: number
  group: MuscleGroup | null
  card: MuscleCardImage | null
}

/**
 * השם שלנו לשרירים שאינם תת-שריר.
 *
 * שלושה כרטיסים מדברים על אותו דבר בשלושה שמות — "מייצבים", "שרירי מייצבים",
 * "מייצבי גו" — ולטקסונומיה אין להם ערך כי הם אינם שריר שבונים סביבו אימון
 * (`NOT_A_SUBTARGET`). מילה אחת שלנו עדיפה על שלוש מודפסות.
 */
const STABILIZERS = 'מייצבים'

/**
 * שתי שורות שאנחנו קוראים להן אותו שם הן שורה אחת.
 *
 * ארבעה-עשר מ-88 הכרטיסים מפרקים שריר לראשים שלו: הארכת ברך היא ארבע שורות
 * שכולן ארבע-ראשי (45+25+20+10), וכפיפת שורש כף יד היא שלוש שורות של כופפי
 * אמה. הטקסונומיה כבר הכריעה שזה שריר אחד — "אף אחד לא בונה אימון סביב
 * הוואסטוס אינטרמדיוס" — ומרגע שההכרעה הזו היא השם היחיד שמוצג, ארבע שורות
 * זהות עם ארבעה מספרים שונים הן תצוגה שבורה.
 *
 * החיבור מותר כאן ואסור במקום אחר, וההבדל הוא הסכום: כרטיס שמסתכם ב-100 הוא
 * חלוקה של אותה עוגה, ולכן חיבור פרוסות שלה הוא אותה עוגה בדיוק ולא מספר
 * חדש. כרטיס שאינו מסתכם ב-100 אינו חלוקה — ראו `NOT_A_PARTITION`.
 */
function mergeSameMuscle(shares: readonly LoadShare[]): LoadShare[] {
  const byName = new Map<string, LoadShare>()
  for (const share of shares) {
    const seen = byName.get(share.name)
    // הראשון קובע את הזהות — הוא בעל האחוז הגבוה, כי הרשימה כבר ממוינת
    if (!seen) byName.set(share.name, { ...share })
    else byName.set(share.name, { ...seen, pct: seen.pct + share.pct, parts: seen.parts + 1 })
  }
  return [...byName.values()].sort((a, b) => b.pct - a.pct)
}

/**
 * הכרטיסים שאינם חלוקה של 100%, ולכן אין להם מפה.
 *
 * שניים מתוך 88, ושניהם מסיבה אמיתית שקריאה על התמונה עצמה:
 *
 *   • `dumbbell_wrist_curl` (סכום 200) — כרטיס אחד ועליו *שני* תרגילים,
 *     כפיפת שורש כף יד ופשיטה. כל אחד מהם 100% בפני עצמו.
 *   • `seated_cable_row_2` (סכום 150) — הרחב-גבי מופיע גם כשלם (50%) וגם
 *     בשני אזורים בתוכו (27% ו-23%). חיבור שלושתם היה מכריז 100% על שריר
 *     שהכרטיס נותן לו חצי.
 *
 * בשני המקרים כל מספר שהיינו מציגים היה הכרעה שלנו ולא של הכרטיס, ולכן
 * הגלריה מציגה את התמונה בלבד — בדיוק כמו שהייתה לפני שהמפה נולדה. שני
 * התרגילים שנוגעים בהם (`low-row-rack`, `lib-seated_cable_row`) מחזיקים
 * כרטיס נוסף שכן מקבל מפה.
 */
const NOT_A_PARTITION: ReadonlySet<string> = new Set([
  'dumbbell_wrist_curl',
  'seated_cable_row_2',
])

/** האחוזים של כרטיס אחד — בשמות שלנו, ממוזגים, מהגדול לקטן */
export function loadMapFor(imageId: string): readonly LoadShare[] {
  const shares = MUSCLE_BREAKDOWN[imageId]
  if (!shares || NOT_A_PARTITION.has(imageId)) return []
  /*
    מיון יורד לפני המיזוג, ו-`sort` יציב — כך השורה הראשונה של כל שריר היא
    הגדולה שלו, והיא זו שנושאת את הזהות (השם האנגלי, הקבוצה, הכרטיס).
  */
  const named = [...shares]
    .sort((a, b) => b.pct - a.pct)
    .map((share) => {
      const taxon = MUSCLE_TAXONOMY[share.en] ?? null
      const name = taxon?.sub ?? STABILIZERS
      return {
        name,
        en: share.en,
        printed: share.he === name ? null : share.he,
        pct: share.pct,
        parts: 1,
        group: taxon?.group ?? null,
        card: taxon ? muscleCardFor(taxon.sub) : null,
      }
    })
  return mergeSameMuscle(named)
}

/**
 * המפה של תמונה בגלריה, או רשימה ריקה.
 *
 * ריקה בשלושה מצבים שכולם לגיטימיים: כרטיס שאין עליו אחוזים כלל (יש כאלה —
 * ‏`IMAGES_WITHOUT_PERCENTAGES`), תמונה שאינה במניפסט, וכרטיס שאינו חלוקה של
 * 100%. הקורא מציג את התמונה בדיוק כמו קודם.
 */
export function loadMapForImage(image: ExerciseImage): readonly LoadShare[] {
  return loadMapFor(imageIdOf(image.src))
}
